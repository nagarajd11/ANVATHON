export const toLocalizedMandiName = (name = '', lang = 'en') => {
  if (!name) return '';
  if (lang === 'kn') {
    if (KANNADA_MARKET_NAMES[name]) return KANNADA_MARKET_NAMES[name];
    return name
      .replace(/\bAPMC\b/gi, 'ಎಪಿಎಂಸಿ')
      .replace(/\bMarket Yard\b/gi, 'ಮಾರುಕಟ್ಟೆ')
      .replace(/\bYard\b/gi, 'ಯಾರ್ಡ್')
      .replace(/\bSub-Yard\b/gi, 'ಉಪ-ಯಾರ್ಡ್');
  }
  return name;
};

export const toLocalizedDistrict = (district = '', lang = 'en') => {
  if (!district) return '';
  if (lang === 'kn') {
    return KANNADA_DISTRICTS[district] || district;
  }
  if (lang === 'hi') {
    return HINDI_DISTRICTS[district] || district;
  }
  return district;
};
